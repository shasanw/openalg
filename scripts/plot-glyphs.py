"""Regenerate src/engine/plotGlyphs.ts: New Computer Modern glyph outlines for graph labels.

plot() (src/engine/plot.ts) draws every label as glyph outlines instead of SVG
<text>. A graph reaches the screen as an image (Typst's SVG pages embed it as a
data: URI, the Add Section picker as an <img>), and an image cannot use the
page's web fonts, so <text> would fall back to a system serif on screen while
the PDF used New Computer Modern. Outlines look the same everywhere.

Run from the repository root (needs fontTools: `pip install fonttools`):
    python3 scripts/plot-glyphs.py
"""

import json
from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.ttLib import TTFont

FONTS = "src/platform/typst/assets/fonts"
OUT = "src/engine/plotGlyphs.ts"
LOWER = "abcdefghijklmnopqrstuvwxyz"
UPPER = LOWER.upper()
# Greek letters as Typst math sets them: the math italic alphabet of the math
# font (U+1D6FC for alpha onwards), stored under the plain Greek character.
GREEK = "αβγδθλμπρσφω"
MATH_ITALIC_GREEK = {ch: 0x1D6FC + "αβγδεζηθικλμνξοπρςστυφχψω".index(ch) for ch in GREEK}
# Each style: a list of (font file, characters, {character: code point to draw it from}).
SETS = {
    # Units (cm, ft) are upright; so are digits, signs and the degree sign.
    "regular": [("NewCM10-Regular.otf", "0123456789−+/√().,=: °?" + LOWER, {})],
    "italic": [
        ("NewCM10-Italic.otf", LOWER + UPPER, {}),
        ("NewCMMath-Regular.otf", GREEK, MATH_ITALIC_GREEK),
    ],
}


def fmt(v):
    r = round(v)
    return str(r)


class IntPen(SVGPathPen):
    def __init__(self, glyphset):
        super().__init__(glyphset, ntos=fmt)


def extract(file, chars, source):
    font = TTFont(f"{FONTS}/{file}")
    cmap = font.getBestCmap()
    glyphset = font.getGlyphSet()
    out = {}
    for ch in chars:
        name = cmap[source.get(ch, ord(ch))]
        pen = IntPen(glyphset)
        glyphset[name].draw(pen)
        out[ch] = [glyphset[name].width, pen.getCommands()]
    return out


tables = {
    style: {ch: g for args in sets for ch, g in extract(*args).items()} for style, sets in SETS.items()
}
lines = [
    "// GENERATED by scripts/plot-glyphs.py from the bundled New Computer Modern",
    "// fonts (SIL Open Font License). Do not edit by hand.",
    "//",
    "// Glyph outlines for graph labels, in font units (1000 per em, y up):",
    "// [advance width, SVG path data]. plot() draws labels with these instead of",
    "// SVG <text> so they look the same in the browser and in the PDF.",
    "",
    "export type GlyphTable = Readonly<Record<string, readonly [number, string]>>;",
    "",
    "export const UNITS_PER_EM = 1000;",
    "",
]
for style, table in tables.items():
    lines.append(f"export const {style.upper()}: GlyphTable = {{")
    for ch, (adv, d) in table.items():
        lines.append(f"  {json.dumps(ch, ensure_ascii=False)}: [{adv}, {json.dumps(d)}],")
    lines.append("};")
    lines.append("")
open(OUT, "w").write("\n".join(lines))
print("wrote", OUT)
