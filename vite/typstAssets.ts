// Build support for the Typst-WASM runtime files (ADR 0002, issue #24):
//
// - `typstAssetBytes()`: their total uncompressed size, so the Preview can
//   show download progress.
// - `typstServiceWorker()`: emits `sw.js`, a service worker that caches those
//   files cache-first by URL. Their names carry content hashes, so a cached
//   URL never goes stale; the cache name is derived from those names, so a
//   deploy that changes any of them starts a new cache and deletes the old.
// - Precompressed `.br` / `.gz` siblings of the large files, for static hosts
//   that serve precompressed files. The compiler WASM is 28 MB raw, ~7 MB
//   brotli and ~11 MB gzip, so brotli matters (RESULTS.md, spike #22).
//   Brotli quality 11 on the WASM takes ~30 s, so results are cached in
//   node_modules/.cache by content hash.

import { createHash } from "node:crypto";
import { existsSync, mkdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { join } from "node:path";
import { brotliCompressSync, constants, gzipSync } from "node:zlib";
import type { Plugin, ResolvedConfig } from "vite";
import { FONT_FILES, MITEX_PACKAGE_FILE } from "../src/platform/typst/assetFiles";

const require = createRequire(import.meta.url);
const root = new URL("..", import.meta.url).pathname;

const SOURCE_FILES = [
  require.resolve("@myriaddreamin/typst-ts-web-compiler/pkg/typst_ts_web_compiler_bg.wasm"),
  require.resolve("@myriaddreamin/typst-ts-renderer/pkg/typst_ts_renderer_bg.wasm"),
  ...FONT_FILES.map((f) => join(root, "src/platform/typst/assets/fonts", f)),
  join(root, "src/platform/typst/assets", MITEX_PACKAGE_FILE),
];

/** Uncompressed bytes of every Typst runtime file. */
export function typstAssetBytes(): number {
  return SOURCE_FILES.reduce((sum, f) => sum + statSync(f).size, 0);
}

/** Emitted file name (without hash) prefixes of the Typst runtime files. */
const ASSET_PREFIXES = [
  "typst_ts_web_compiler_bg-",
  "typst_ts_renderer_bg-",
  ...FONT_FILES.map((f) => f.replace(/\.otf$/, "-")),
  MITEX_PACKAGE_FILE.replace(/\.gz$/, "-"),
];

const isTypstAsset = (fileName: string) => {
  const base = fileName.split("/").pop()!;
  return ASSET_PREFIXES.some((p) => base.startsWith(p));
};

const PRECOMPRESS = /\.(wasm|otf|js|css|html|svg|json|webmanifest)$/;

function serviceWorkerSource(cacheName: string, urls: string[]): string {
  return `// Generated by vite/typstAssets.ts. Caches the Typst compiler, renderer,
// fonts and mitex package cache-first so they download once (ADR 0002). Only
// those content-hashed URLs are handled; everything else goes to the network
// untouched.
const PREFIX = "openalg-typst-";
const CACHE = ${JSON.stringify(cacheName)};
const ASSETS = new Set(${JSON.stringify(urls)}.map((u) => new URL(u, self.registration.scope).pathname));

self.addEventListener("install", () => self.skipWaiting());

self.addEventListener("activate", (event) => {
  event.waitUntil(
    (async () => {
      for (const key of await caches.keys()) {
        if (key.startsWith(PREFIX) && key !== CACHE) await caches.delete(key);
      }
      await self.clients.claim();
    })(),
  );
});

async function cached(request) {
  const cache = await caches.open(CACHE);
  const hit = await cache.match(request, { ignoreVary: true });
  if (hit) return hit;
  const response = await fetch(request);
  if (response.ok && response.type === "basic") await cache.put(request, response.clone());
  return response;
}

self.addEventListener("fetch", (event) => {
  const { request } = event;
  if (request.method !== "GET") return;
  const url = new URL(request.url);
  if (url.origin !== self.location.origin || !ASSETS.has(url.pathname)) return;
  event.respondWith(cached(request));
});

// The page sends this once it has downloaded the files itself on a first
// visit (before this worker controlled it). Fetching them again here is
// normally answered by the HTTP cache.
self.addEventListener("message", (event) => {
  if (event.data?.type !== "cache-typst-assets") return;
  event.waitUntil(
    (async () => {
      const cache = await caches.open(CACHE);
      for (const path of ASSETS) {
        if (await cache.match(path, { ignoreVary: true })) continue;
        try {
          const response = await fetch(path);
          if (response.ok) await cache.put(path, response);
        } catch {
          // Try again on the next visit.
        }
      }
    })(),
  );
});
`;
}

function compressCached(data: Buffer, kind: "br" | "gz"): Buffer {
  const hash = createHash("sha256").update(data).digest("hex");
  const dir = join(root, "node_modules/.cache/openalg-precompress");
  const file = join(dir, `${hash}.${kind}`);
  if (existsSync(file)) return readFileSync(file);
  const out =
    kind === "br"
      ? brotliCompressSync(data, {
          params: {
            [constants.BROTLI_PARAM_QUALITY]: 11,
            [constants.BROTLI_PARAM_SIZE_HINT]: data.length,
          },
        })
      : gzipSync(data, { level: 9 });
  mkdirSync(dir, { recursive: true });
  writeFileSync(file, out);
  return out;
}

export function typstServiceWorker(): Plugin {
  let config: ResolvedConfig;
  return {
    name: "openalg-typst-service-worker",
    apply: "build",
    configResolved(resolved) {
      config = resolved;
    },
    generateBundle(_options, bundle) {
      const files = Object.keys(bundle).filter(isTypstAsset).sort();
      const missing = ASSET_PREFIXES.filter(
        (p) => !files.some((f) => f.split("/").pop()!.startsWith(p)),
      );
      if (missing.length) {
        this.error(`Typst runtime files missing from the build: ${missing.join(", ")}`);
      }
      const version = createHash("sha256").update(files.join("\n")).digest("hex").slice(0, 12);
      const urls = files.map((f) => `./${f}`);
      this.emitFile({
        type: "asset",
        fileName: "sw.js",
        source: serviceWorkerSource(`openalg-typst-${version}`, urls),
      });
    },
    writeBundle(options, bundle) {
      const outDir = options.dir ?? config.build.outDir;
      for (const [fileName, item] of Object.entries(bundle)) {
        if (!PRECOMPRESS.test(fileName)) continue;
        const data = Buffer.from(item.type === "asset" ? item.source : item.code);
        if (data.length < 1024) continue;
        for (const kind of ["br", "gz"] as const) {
          writeFileSync(join(outDir, `${fileName}.${kind}`), compressCached(data, kind));
        }
      }
    },
  };
}
